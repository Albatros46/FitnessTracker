-- Fitness Tracker - PostgreSQL schema
-- Mirrors the JPA entities in FitnessTrackerServer (com.server.entity).
-- Hibernate (ddl-auto=update) can create these tables on its own; this script
-- documents the schema and adds the constraints the API already enforces.

CREATE TABLE IF NOT EXISTS activity (
    id              BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    date            DATE             NOT NULL,
    steps           INTEGER          NOT NULL CHECK (steps >= 0),
    distance        DOUBLE PRECISION NOT NULL CHECK (distance >= 0),
    calories_burned INTEGER          NOT NULL CHECK (calories_burned >= 0)
);

CREATE TABLE IF NOT EXISTS workout (
    id              BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    type            VARCHAR(255) NOT NULL,
    date            DATE         NOT NULL,
    duration        INTEGER      NOT NULL CHECK (duration > 0),
    calories_burned INTEGER      NOT NULL CHECK (calories_burned >= 0)
);

CREATE TABLE IF NOT EXISTS goal (
    id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    description VARCHAR(255) NOT NULL,
    start_date  DATE         NOT NULL,
    end_date    DATE         NOT NULL,
    achieved    BOOLEAN      NOT NULL DEFAULT FALSE,
    CONSTRAINT goal_date_range CHECK (end_date >= start_date)
);

-- Lists are sorted by date (activities, workouts) and end date (goals).
CREATE INDEX IF NOT EXISTS idx_activity_date ON activity (date);
CREATE INDEX IF NOT EXISTS idx_workout_date ON workout (date);
CREATE INDEX IF NOT EXISTS idx_goal_end_date ON goal (end_date);
